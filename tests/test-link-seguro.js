const { chromium } = require('playwright');
const fs = require('fs');
const FAKE = fs.readFileSync('tests/test-cartao-aprovado.js', 'utf8').match(/const FAKE_SDK = `([\s\S]*?)`;/)[1];
(async () => {
  const base = 'http://127.0.0.1:3978';
  const b = await chromium.launch({ args: ['--no-sandbox'] });
  const c = await b.newContext({ viewport: { width: 390, height: 900 }, deviceScaleFactor: 2 });
  const p = await c.newPage();
  const erros = [];
  p.on('pageerror', (e) => erros.push(e.message));
  await p.addInitScript(FAKE);
  await p.route('https://mp.test/**', (r) => r.fulfill({ status: 200, contentType: 'text/html', body: '<h1>Página segura do Mercado Pago (teste)</h1>' }));
  await p.goto(base + '/l/pratica-sabores', { waitUntil: 'networkidle' });
  await p.waitForTimeout(900);
  await p.locator('button').filter({ hasText: /adicionar|\+/i }).first().click();
  await p.waitForTimeout(400);
  await p.locator('#cartBarBtn').click();
  await p.waitForTimeout(400);
  await p.locator('button').filter({ hasText: /finalizar|continuar|fechar pedido|ir para o pagamento/i }).first().click();
  await p.waitForTimeout(700);
  await p.fill('input[name="customer_name"]', 'Ana Link');
  await p.fill('input[name="phone"]', '48977776666');
  const addr = p.locator('input[name="address"]');
  if (await addr.count()) await addr.first().fill('Rua Link 10, Centro');
  await p.locator('input[name="payment_method"][data-pay-id="cartao_online"]').check({ force: true });
  await p.waitForTimeout(700);
  const popupPromessa = c.waitForEvent('page', { timeout: 8000 }).catch(() => null);
  await p.locator('#mpLinkSeguro').click();
  const popup = await popupPromessa;
  console.log('abriu a página segura:', popup ? popup.url() : 'não abriu');
  await p.waitForTimeout(1500);
  const corpo = await p.locator('.drawer-body').innerText().catch(() => '');
  console.log('tela:', corpo.replace(/\n+/g, ' | ').slice(0, 260));
  const botoes = await p.locator('.drawer-foot a').evaluateAll((els) => els.map((e) => e.textContent.trim() + ' -> ' + e.href.slice(0, 60)));
  console.log('botões rodapé:', botoes);
  await p.screenshot({ path: 'tests/shots/JG-link-seguro.png' });
  console.log('ERROS:', erros.length ? erros : 0);
  await b.close();
})();
